  const history = {};

  function currentLang() {
    return (SNK.i18n && SNK.i18n.lang === 'zh') ? 'zh' : 'en';
  }

  function pick(level, category, ctx) {
    const set = PROFILES[level] || GENERIC;
    const list = set[category] || GENERIC[category] || [];
    if (!list.length) return '';
    const key = level + '|' + category;
    const recent = history[key] || (history[key] = []);
    let line = list[0];
    for (let tries = 0; tries < 10; tries++) {
      line = list[(Math.random() * list.length) | 0];
      if (recent.indexOf(line.en) < 0) break;
    }
    recent.push(line.en);
    if (recent.length > Math.min(3, list.length - 1)) recent.shift();

    const lang = currentLang();
    let text = line[lang] || line.en;
    const c = ctx || {};
    return text
      .replace(/\{name\}/g, c.name || set.name || 'AI')
      .replace(/\{opponent\}/g, c.opponent || (lang === 'zh' ? '你' : 'you'))
      .replace(/\{break\}/g, c.break === undefined ? '' : String(c.break))
      .replace(/\{points\}/g, c.points === undefined ? '' : String(c.points));
  }

